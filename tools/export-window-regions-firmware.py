#!/usr/bin/env python3
"""Export small palette panoramas without changing existing artwork or partitions."""
from pathlib import Path
from PIL import Image
import json, hashlib
R=Path(__file__).resolve().parents[1]
A=R/'assets/art-v1/window-regions-v1'
B=R/'vendor/xiaozhi-esp32/main/boards/waveshare/esp32-s3-touch-amoled-2.16'
O=A/'firmware'; O.mkdir(exist_ok=True)
out=['// Generated by tools/export-window-regions-firmware.py.','namespace spring_scenery {']
records=[]
for region in ['wasteland','rain_city','tunnel','forest']:
 for kind,size,n in [('far',(128,64),256),('near',(160,48),64)]:
  im=Image.open(A/'layers'/f'{region}-{kind}.png').convert('RGBA').resize(size,Image.Resampling.LANCZOS)
  pal=im.quantize(colors=n,method=Image.Quantize.FASTOCTREE,dither=Image.Dither.NONE)
  rgba=pal.convert('RGBA'); colors=bytearray(n*4); indices=bytes(pal.getdata())
  for i,c in zip(indices,rgba.getdata()): colors[i*4:i*4+4]=bytes(c)
  if n==256:
   pixels=indices
  else:
   packed=bytearray()
   for i in range(0,len(indices),4):
    a,b,c,d=indices[i:i+4]
    packed.extend(((a<<2)|(b>>4),((b&15)<<4)|(c>>2),((c&3)<<6)|d))
   pixels=bytes(packed)
   unpacked=[]
   for i in range(0,len(pixels),3):
    a,b,c=pixels[i:i+3];unpacked.extend((a>>2,((a&3)<<4)|(b>>4),((b&15)<<2)|(c>>6),c&63))
   assert bytes(unpacked)==indices
  raw=colors+pixels; name=f'{region}_{kind}'
  (O/f'{name}.bin').write_bytes(raw); rgba.save(O/f'{name}.png')
  out.append(f'alignas(4) const uint8_t {name}[] = {{')
  out.extend(','.join(map(str,raw[i:i+32]))+',' for i in range(0,len(raw),32))
  out.append('};')
  records.append(dict(name=name,bytes=len(raw),sha256=hashlib.sha256(raw).hexdigest()))
rack=Image.open(R/'assets/art-v1/economy/layout-v3/equipment-split/rack-empty.png').convert('RGBA').resize((147,229),Image.Resampling.LANCZOS)
mask=bytearray(18*106)
for y in range(106):
 for x in range(140):
  if rack.getpixel((x+7,y))[3] > 0: mask[y*18+x//8] |= 128>>(x%8)
(O/'rack-occlusion-mask.bin').write_bytes(mask)
out.append('const uint8_t kRackMask[] = {')
out.extend(','.join(map(str,mask[i:i+32]))+',' for i in range(0,len(mask),32))
out.append('};')
records.append(dict(name='rack-occlusion-mask',bytes=len(mask),sha256=hashlib.sha256(mask).hexdigest()))
out+=['const Region kRegions[4] = {']
out += [f'    {{{r}_far, {r}_near}},' for r in ['wasteland','rain_city','tunnel','forest']]
out += ['};','}']
(B/'spring_scenery_data.inc').write_text('\n'.join(out)+'\n')
(O/'manifest.json').write_text(json.dumps(dict(assets=records,bytes=sum(r['bytes'] for r in records)),indent=2)+'\n')
print('New scene bytes:',sum(r['bytes'] for r in records))
