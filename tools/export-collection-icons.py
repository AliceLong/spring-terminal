"""Build eight code-drawn 32px resource icons; no source game art is modified."""
import json
import math
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
BOARD = ROOT / "vendor/xiaozhi-esp32/main/boards/waveshare/esp32-s3-touch-amoled-2.16"
OUT = ROOT / "assets/harvest-v56"
OUT.mkdir(parents=True, exist_ok=True)
SCALE = 4


def icon(kind, frame):
    im = Image.new("RGBA", (128, 128))
    d = ImageDraw.Draw(im)

    def poly(points, color):
        d.polygon([(round(x * SCALE), round(y * SCALE)) for x, y in points], fill=color)

    def ellipse(box, color):
        d.ellipse(tuple(round(x * SCALE) for x in box), fill=color)

    def line(points, color, width):
        d.line([(round(x * SCALE), round(y * SCALE)) for x, y in points],
               fill=color, width=round(width * SCALE), joint="curve")

    if kind == 0:
        poly([(16, 1), (10, 9), (5, 17), (5, 23), (9, 28), (16, 31),
              (23, 28), (27, 23), (27, 17), (22, 9)], "#264f6c")
        poly([(16, 4), (11, 12), (7, 18), (7, 23), (11, 27), (16, 29),
              (23, 25), (25, 21), (23, 15)], "#3cadd2")
        poly([(17, 7), (17, 20), (24, 22), (22, 15)], "#8bdcf0")
        poly([(9, 23), (14, 27), (20, 27), (24, 23), (19, 24)], "#16839d")
        line([(13, 11), (10, 16), (10, 19)], "#f2ffff", 2)
        ellipse((17, 22, 20, 25), "#b6f2f7" if frame else "#89dbe8")
    elif kind == 1:
        poly([(13, 1), (25, 9), (27, 19), (18, 31), (7, 27), (4, 15)], "#735033")
        poly([(13, 3), (23, 10), (25, 18), (17, 28), (9, 25), (6, 15)], "#e7a531")
        poly([(13, 4), (14, 15), (7, 15)], "#fff1a2")
        poly([(13, 4), (22, 11), (14, 15)], "#ffd86b")
        poly([(14, 15), (22, 11), (24, 18), (17, 27)], "#b96e28")
        poly([(7, 16), (14, 16), (17, 27), (9, 24)], "#f4bd45")
        line([(14, 6), (15, 13)], "#fff8d5", 1)
        if frame:
            line([(27, 2), (27, 8)], "#ffedb5", 1)
            line([(24, 5), (30, 5)], "#ffedb5", 1)
    elif kind == 2:
        points = []
        for i in range(80):
            t = i / 79
            angle = -math.pi * .8 + t * math.pi * 3.1
            radius = 11 - t * 8
            points.append((16 + math.cos(angle) * radius, 15 + math.sin(angle) * radius))
        line(points, "#394e32", 5)
        line(points, "#9aa85a", 3)
        line([(x - .6, y - .6) for x, y in points], "#d4d893", .8)
        line([(7, 24), (12, 29), (23, 26)], "#627d43", 2)
        line([(23, 26), (28, 24)], "#d5d39b", 1)
        line([(23, 26), (27, 29)], "#9cb16a", 1)
        if frame:
            line([(22, 7), (25, 7)], "#f4ecc0", 1.5)
    else:
        poly([(5, 25), (8, 12), (19, 5), (28, 4), (27, 16), (20, 24), (10, 28)], "#3b6035")
        poly([(8, 24), (11, 13), (20, 8), (25, 7), (24, 16), (18, 22)],
             "#a1bb59" if frame else "#8fa74e")
        line([(5, 29), (12, 21), (22, 11)], "#d7d993", 1.2)
        line([(14, 19), (13, 13)], "#d7d993", .7)
        line([(17, 16), (23, 16)], "#d7d993", .7)
    return im.resize((32, 32), Image.Resampling.LANCZOS)


parts = ['// Generated by tools/export-collection-icons.py.\n#include "spring_collection_assets.h"\nnamespace spring_collection { namespace {\n']
manifest = []
for kind, name in enumerate(("water", "energy", "fiber", "leaf")):
    for frame in range(2):
        im = icon(kind, frame)
        im.save(OUT / f"{name}-{frame}.png")
        rgb = bytearray()
        alpha = bytearray()
        for r, g, b, a in im.getdata():
            value = (r >> 3) << 11 | (g >> 2) << 5 | b >> 3
            rgb.extend((value & 255, value >> 8))
            alpha.append(a)
        raw = rgb + alpha
        symbol = f"{name}_{frame}"
        parts.append(f"alignas(4) const uint8_t {symbol}[] = {{\n")
        parts.extend(",".join(map(str, raw[i:i + 32])) + ",\n" for i in range(0, len(raw), 32))
        parts.append("};\n")
        manifest.append(dict(name=symbol, width=32, height=32, format="RGB565A8", bytes=len(raw)))
parts.append("const lv_image_dsc_t images[] = {\n")
for row in manifest:
    parts.append("{{.magic=LV_IMAGE_HEADER_MAGIC,.cf=LV_COLOR_FORMAT_RGB565A8,.flags=0,"
                 ".w=32,.h=32,.stride=64,.reserved_2=0},3072," + row["name"] + ",nullptr,nullptr},\n")
parts.append("};\n}\nconst lv_image_dsc_t* Image(Kind kind, unsigned frame) {\n"
             "return &images[static_cast<unsigned>(kind)*2 + (frame&1)];\n}\n}\n")
(BOARD / "spring_collection_assets.cc").write_text("".join(parts))
(OUT / "manifest.json").write_text(json.dumps(dict(frames=manifest, flash_pixels=sum(x["bytes"] for x in manifest)), indent=2) + "\n")
print(f"8 native 32px frames: {sum(x['bytes'] for x in manifest)} pixel bytes; source art unchanged")
