#!/usr/bin/env python3
"""Pack generated art into LVGL raw images; no runtime PNG decoding required."""
import json
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'assets/runtime'
BOARD = ROOT / 'vendor/xiaozhi-esp32/main/boards/waveshare/esp32-s3-touch-amoled-2.16'
OUT.mkdir(parents=True, exist_ok=True)
background = Image.open(ROOT / 'assets/source/desk-scene-v1.png').convert('RGB')
background = background.resize((240, 240), Image.Resampling.LANCZOS)
background.save(OUT / 'desk-scene-240.png')
atlas = Image.open(ROOT / 'assets/source/sproutling-atlas-v1.png').convert('RGBA')
assert atlas.getextrema()[3][0] == 0, 'Sprite sheet must have real transparency'
cells = []
for row in range(2):
    for col in range(4):
        cell = atlas.crop((col * atlas.width // 4, row * atlas.height // 2,
                           (col + 1) * atlas.width // 4, (row + 1) * atlas.height // 2))
        bounds = cell.getchannel('A').point(lambda a: 255 if a > 32 else 0).getbbox()
        assert bounds
        cells.append(cell.crop(bounds))
# A common scale preserves relative pose size; all feet share the same baseline.
scale = min(44 / max(c.width for c in cells), 52 / max(c.height for c in cells))
frames = []
for index, cell in enumerate(cells):
    cell = cell.resize((round(cell.width * scale), round(cell.height * scale)),
                       Image.Resampling.LANCZOS)
    frame = Image.new('RGBA', (48, 56))
    frame.alpha_composite(cell, ((48 - cell.width) // 2, 54 - cell.height))
    frame.save(OUT / f'sproutling-{index}.png')
    frames.append(frame)

def rgb565(image):
    data = bytearray()
    for r, g, b in image.getdata():
        value = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        data.extend(value.to_bytes(2, 'little'))
    return data

def bgra(image):
    return bytes(channel for r, g, b, a in image.getdata() for channel in (b, g, r, a))

physical_background = background.resize((480, 480), Image.Resampling.NEAREST)
physical_frames = [f.resize((96, 112), Image.Resampling.NEAREST) for f in frames]
images = [('desk_scene_v1', physical_background, 'RGB565', rgb565(physical_background))]
images += [(f'sproutling_v1_{i}', f, 'ARGB8888', bgra(f)) for i, f in enumerate(physical_frames)]
header = ['#pragma once', '#include <lvgl.h>', '#ifdef __cplusplus', 'extern "C" {', '#endif']
source = ['// Generated by tools/prepare-scene-assets.py. Regenerate instead of editing.',
          '#include "scene_assets.h"']
for name, img, fmt, data in images:
    header.append(f'extern const lv_image_dsc_t {name};')
    source.append(f'static const uint8_t {name}_data[] __attribute__((aligned(4))) = {{')
    source += ['    ' + ','.join(f'0x{x:02x}' for x in data[i:i+24]) + ','
               for i in range(0, len(data), 24)]
    source.append('};')
    stride = img.width * (2 if fmt == 'RGB565' else 4)
    source.append(f'''const lv_image_dsc_t {name} = {{
    .header = {{.magic=LV_IMAGE_HEADER_MAGIC, .cf=LV_COLOR_FORMAT_{fmt},
               .w={img.width}, .h={img.height}, .stride={stride}}},
    .data_size=sizeof({name}_data), .data={name}_data
}};''')
header += ['#ifdef __cplusplus', '}', '#endif']
(BOARD / 'scene_assets.h').write_text('\n'.join(header) + '\n')
(BOARD / 'scene_assets.c').write_text('\n'.join(source) + '\n')
(OUT / 'manifest.json').write_text(json.dumps({
    'logical_background': [240, 240], 'background': [480, 480, 'RGB565'],
    'sprites': [8, 96, 112, 'ARGB8888'],
    'raw_bytes': sum(len(x[3]) for x in images),
    'notes': 'Generated atlas frame 5 faces right despite prompt; left walk uses frame 4 with a small motion bob.'
}, indent=2) + '\n')
print('Packed', len(images), 'images;', sum(len(x[3]) for x in images), 'raw bytes')
