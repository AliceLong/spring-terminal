#!/usr/bin/env python3
"""Convert reviewed art to small LVGL RGB565A8 frames and one deflate pack.

This is deterministic firmware encoding/resampling, not source-art retouching.
Original RGBA source atlases remain unchanged. Decode once on boot, never in audio paths.
"""
import hashlib
import json
import struct
import zlib
from pathlib import Path
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent.parent
ART = ROOT / 'assets/art-v2-20261018'
OUT = ROOT / 'assets/runtime-v2'
BOARD = ROOT / 'vendor/xiaozhi-esp32/main/boards/waveshare/esp32-s3-touch-amoled-2.16'
OUT.mkdir(exist_ok=True)
assets = json.loads((ART / 'manifest.json').read_text())['assets']
raw = bytearray()
frames = []
groups = []

def append(image, alpha=True):
    while len(raw) % 4:
        raw.append(0)
    start = len(raw)
    rgb = bytearray()
    mask = bytearray()
    for r,g,b,a in image.convert('RGBA').getdata():
        if alpha and a == 0:
            r=g=b=0
        rgb.extend(struct.pack('<H', ((r>>3)<<11)|((g>>2)<<5)|(b>>3)))
        mask.append(a)
    raw.extend(rgb)
    if alpha:
        raw.extend(mask)
    frames.append((start, len(raw)-start, image.width, image.height, alpha))

background = Image.open(ROOT / 'assets/source/desk-scene-v1.png').convert('RGBA')
background = background.resize((480,480), Image.Resampling.LANCZOS)
append(background, False)
for asset in assets:
    image = Image.open(ART / asset['file']).convert('RGBA')
    cells = [image.crop((x,y,x+w,y+h)) for x,y,w,h in asset['content_bounds']]
    sizes = {'bottle_cap_table':(48,44), 'storage_rack':(40,48),
             'bottle_cap':(24,18), 'cotton':(28,22), 'paperclip':(16,28),
             'stick':(32,16), 'paper_scrap':(24,18), 'discovery':(24,24),
             'wood_chips':(24,24), 'sleep_motes':(24,24), 'resonance':(32,32),
             'delivery_portal':(48,24)}
    w,h = sizes.get(asset['id'], asset['logical_cell'])
    # Shared scale and foot anchor within a group preserve movement and pose height.
    scale = min((w-4)/max(c.width for c in cells), (h-4)/max(c.height for c in cells))
    rendered = []
    for cell in cells:
        cell = cell.resize((max(1,round(cell.width*scale)),max(1,round(cell.height*scale))),Image.Resampling.LANCZOS)
        frame = Image.new('RGBA',(w,h))
        frame.alpha_composite(cell,((w-cell.width)//2,h-2-cell.height))
        rendered.append(frame)
    first = len(frames)
    for i,frame in enumerate(rendered):
        append(frame)
        frame.save(OUT / f"{asset['id']}-{i}.png")
    mirror = first
    if asset['category'] == 'character':
        mirror = len(frames)
        for frame in rendered:
            append(ImageOps.mirror(frame))
    groups.append((asset['id'],first,len(rendered),mirror))
    if asset['id'] == 'soft_bed':
        front_first = len(frames)
        for frame in rendered:
            front = frame.copy()
            front.paste((0,0,0,0),(0,0,front.width,front.height-10))
            append(front)
        groups.append(('soft_bed_front',front_first,len(rendered),front_first))

compressed = zlib.compress(bytes(raw),9)
assert zlib.decompress(compressed)==raw
(OUT/'scene-art.deflate').write_bytes(compressed)
header = ['// Generated by tools/prepare-scene-v2.py; do not edit.', '#pragma once', '#include <stdint.h>', '#include <stdbool.h>', '#ifdef __cplusplus','extern "C" {','#endif',
          'typedef struct { uint32_t offset, size; uint16_t width, height; bool alpha; } ScenePackedFrame;',
          'typedef struct { uint16_t first, count, mirror; } ScenePackedGroup;',
          'typedef enum {']
for i,(name,first,count,mirror) in enumerate(groups):
    header.append(f'    SCENE_ART_{name.upper()} = {i},')
header += ['    SCENE_ART_COUNT','} SceneArtKind;',f'#define SCENE_ART_FRAME_COUNT {len(frames)}',f'#define SCENE_ART_RAW_BYTES {len(raw)}',f'#define SCENE_ART_PACKED_BYTES {len(compressed)}','extern const uint8_t scene_art_deflate[SCENE_ART_PACKED_BYTES];','extern const ScenePackedFrame scene_art_frames[SCENE_ART_FRAME_COUNT];','extern const ScenePackedGroup scene_art_groups[SCENE_ART_COUNT];','#ifdef __cplusplus','}','#endif']
source = ['// Generated by tools/prepare-scene-v2.py; do not edit.','#include "scene_art_pack.h"','const uint8_t scene_art_deflate[SCENE_ART_PACKED_BYTES] __attribute__((aligned(4))) = {']
for i in range(0,len(compressed),24):
    source.append('    '+','.join(f'0x{x:02x}' for x in compressed[i:i+24])+',')
source+=['};','const ScenePackedFrame scene_art_frames[SCENE_ART_FRAME_COUNT] = {']
source += [f'    {{{offset}, {size}, {w}, {h}, {str(alpha).lower()}}},' for offset,size,w,h,alpha in frames]
source+=['};','const ScenePackedGroup scene_art_groups[SCENE_ART_COUNT] = {']
source += [f'    {{{first}, {count}, {mirror}}}, // {name}' for name,first,count,mirror in groups]
source+=['};']
(BOARD/'scene_art_pack.h').write_text('\n'.join(header)+'\n')
(BOARD/'scene_art_pack.c').write_text('\n'.join(source)+'\n')
# Retire v1 arrays through the generator, preserving v1 source atlases and backups.
(BOARD/'scene_assets.c').write_text('// Legacy v1 arrays replaced by scene_art_pack.c; generated by tools/prepare-scene-v2.py.\n')
manifest={'version':2,'format':'RGB565 + planar A8; background RGB565', 'logical_scale':2,'raw_bytes':len(raw),'compressed_bytes':len(compressed),'frames':len(frames),'groups':len(groups),'sha256':hashlib.sha256(compressed).hexdigest(),'decode':'one boot-time allocation in PSRAM; no frame-time allocations or decompression'}
(OUT/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
print(json.dumps(manifest))
